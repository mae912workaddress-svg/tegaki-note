import { mkdir, copyFile, cp, readdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
const root = fileURLToPath(new URL('../', import.meta.url));
const copy = async (from, to) => { const dest = path.join(root, 'vendor', to); await mkdir(path.dirname(dest), { recursive: true }); await copyFile(path.join(root, 'node_modules', from), dest); };
await copy('perfect-freehand/dist/esm/index.mjs', 'perfect-freehand/index.mjs');
await copy('perfect-freehand/LICENSE', 'perfect-freehand/LICENSE');
await copy('pdf-lib/dist/pdf-lib.esm.min.js', 'pdf-lib/pdf-lib.esm.min.js');
await copy('pdf-lib/LICENSE.md', 'pdf-lib/LICENSE.md');
await copy('pdfjs-dist/legacy/build/pdf.min.mjs', 'pdfjs/pdf.mjs');
await copy('pdfjs-dist/legacy/build/pdf.worker.min.mjs', 'pdfjs/pdf.worker.mjs');
await copy('pdfjs-dist/LICENSE', 'pdfjs/LICENSE');
for (const dir of ['cmaps', 'standard_fonts']) await cp(path.join(root, 'node_modules/pdfjs-dist', dir), path.join(root, 'vendor/pdfjs', dir), { recursive: true });
// Deterministic inventory is imported by the classic service worker and tested.
async function walk(dir) {
  const entries = await readdir(path.join(root, dir), { withFileTypes: true });
  const lists = await Promise.all(entries.map(e => e.isDirectory() ? walk(`${dir}/${e.name}`) : [`./${dir}/${e.name}`]));
  return lists.flat().sort();
}
const assets = ['./', './index.html', './manifest.webmanifest', './sw.js', './precache.js', ...(await walk('src')), ...(await walk('icons')), ...(await walk('vendor'))];
await writeFile(path.join(root, 'precache.js'), `// Generated by scripts/copy-vendor.mjs\nself.PRECACHE = ${JSON.stringify(assets, null, 2)};\n`);
console.log(`${assets.length} assets ready (PDF.js legacy build).`);
